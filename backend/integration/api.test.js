import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import mysql from 'mysql2/promise';
import { createApp } from '../src/app.js';
import { config } from '../src/config.js';
import { backup } from '../test/fixture.js';

test('MySQL-backed accounts, isolation, revisions, validation, and logout', async t => {
  const db = mysql.createPool(config.db);
  const server = createApp(db).listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  const emails = [`test-${randomUUID()}@example.invalid`, `test-${randomUUID()}@example.invalid`];
  t.after(async () => {
    await db.execute('DELETE FROM st_users WHERE email IN (?, ?)', emails);
    server.closeAllConnections();
    await new Promise(resolve => server.close(resolve));
    await db.end();
  });
  const request = async (method, path, body, token) => {
    const response = await fetch(`http://127.0.0.1:${server.address().port}${path}`, { method, headers: { 'Content-Type': 'application/json', ...(token ? { Authorization: `Bearer ${token}` } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
    return { status: response.status, body: response.status === 204 ? null : await response.json() };
  };
  assert.equal((await request('GET', '/health')).status, 200);
  assert.equal((await request('GET', '/backup')).status, 401);
  assert.equal((await request('POST', '/auth/register', { name: ' ', email: emails[0], password: 'test-password-123' })).status, 400);
  const first = await request('POST', '/auth/register', { name: 'Alex Reyes', email: emails[0], password: 'test-password-123' });
  const second = await request('POST', '/auth/register', { name: 'Sam Cruz', email: emails[1], password: 'test-password-456' });
  assert.equal(first.status, 201); assert.equal(second.status, 201);
  assert.equal(first.body.name, 'Alex Reyes');
  assert.equal((await request('POST', '/auth/register', { name: 'Other Name', email: emails[0], password: 'test-password-123' })).status, 409);
  assert.equal((await request('POST', '/auth/login', { email: emails[0], password: 'incorrect-password' })).status, 401);
  const loggedIn = await request('POST', '/auth/login', { email: emails[0], password: 'test-password-123' });
  assert.equal(loggedIn.status, 200);
  assert.equal(loggedIn.body.name, 'Alex Reyes');
  const token = loggedIn.body.token;
  assert.equal((await request('PATCH', '/profile', { name: ' ' }, token)).status, 400);
  assert.equal((await request('PATCH', '/profile', { name: 'Other', userId: 1 }, token)).status, 400);
  const profile = await request('PATCH', '/profile', { name: '  Alex   Santos  ' }, token);
  assert.equal(profile.status, 200);
  assert.equal(profile.body.name, 'Alex Santos');
  assert.equal(profile.body.email, emails[0]);
  const signedInAgain = await request('POST', '/auth/login', { email: emails[0], password: 'test-password-123' });
  assert.equal(signedInAgain.body.name, 'Alex Santos');
  const otherAccount = await request('POST', '/auth/login', { email: emails[1], password: 'test-password-456' });
  assert.equal(otherAccount.body.name, 'Sam Cruz');
  assert.equal((await request('GET', '/backup', null, token)).body.data, null);
  assert.equal((await request('PUT', '/backup', { revision: 0, data: backup() }, token)).status, 200);
  const saved = await request('GET', '/backup', null, token);
  assert.equal(saved.body.revision, 1); assert.equal(saved.body.data.expenses[0].title, 'Lunch');
  assert.equal((await request('GET', '/backup', null, second.body.token)).body.data, null);
  assert.equal((await request('PUT', '/backup', { revision: 0, data: backup() }, token)).status, 409);
  const invalid = backup(); invalid.expenses[0].amount = -10;
  assert.equal((await request('PUT', '/backup', { revision: 1, data: invalid }, token)).status, 400);
  const concurrent = await Promise.all([request('PUT', '/backup', { revision: 1, data: backup() }, token), request('PUT', '/backup', { revision: 1, data: backup() }, token)]);
  assert.deepEqual(concurrent.map(value => value.status).sort(), [200, 409]);
  const actual = backup();
  actual.expenses = [];
  actual.bills = [{ name: 'My actual rent', amount: 4500, due: '2026-11-10T00:00:00.000', icon: 5, category: null, repeat: 'Never', reminder: '3 days before', paid: false, notes: 'Pay landlord', paymentReason: '', paymentPlanAt: null, paymentPlanAtMillis: null, followUpRepeat: 'Daily' }];
  assert.equal((await request('PUT', '/backup', { revision: 2, data: actual }, token)).status, 200);
  const billSaved = await request('GET', '/backup', null, token);
  assert.equal(billSaved.body.data.bills[0].name, 'My actual rent');
  actual.bills[0].paid = true;
  assert.equal((await request('PUT', '/backup', { revision: 3, data: actual }, token)).status, 200);
  const signedInForBills = await request('POST', '/auth/login', { email: emails[0], password: 'test-password-123' });
  const billReloaded = await request('GET', '/backup', null, signedInForBills.body.token);
  assert.equal(billReloaded.body.data.bills[0].paid, true);
  assert.equal((await request('GET', '/backup', null, second.body.token)).body.data, null);
  assert.equal((await request('DELETE', '/auth/session', null, token)).status, 204);
  assert.equal((await request('GET', '/backup', null, token)).status, 401);
  await db.execute('UPDATE st_sessions s JOIN st_users u ON u.id = s.user_id SET s.expires_at = DATE_SUB(UTC_TIMESTAMP(), INTERVAL 1 MINUTE) WHERE u.email = ?', [emails[1]]);
  assert.equal((await request('GET', '/backup', null, second.body.token)).status, 401);
});
